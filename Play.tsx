/**
 * BgwsPlay — place both sides, press start, advance a turn at a time.
 *
 * THE SEQUENCE, WHICH IS THE POINT OF THIS SCREEN
 *
 *   1. PLACE    drop counters for both sides anywhere on their own half
 *   2. START    fixes the setup
 *   3. GENERATE each commander is asked ONCE for its whole force's
 *               intentions, against a fog-of-war view of the board; both are
 *               asked before either is executed. NOTHING IS RESOLVED: the
 *               orders are drawn on the map and the turn waits.
 *   4. EXECUTE  the Action-Reaction Round: orders execute in initiative
 *               order, and anything crossing a loaded arc can be shot at
 *               while it moves
 *   5. COUNTER  the Counteraction Round, inside the same press: each
 *               commander is asked a second time, now that it has seen the
 *               round, to commit its reserve and to fire with whatever held
 *               back
 *   6. REPEAT   until one side is gone
 *
 * Four model calls a turn, not fifty — two for the orders and two for the
 * counteraction round. An LLM commander sees its whole force and forms a
 * plan, which is the level a commander actually operates at.
 *
 * WHY THE TURN IS TWO PRESSES
 *
 * A commander's plan is the most interesting thing on this screen and it used
 * to be invisible: orders were generated and resolved inside one click, so
 * all anyone ever saw was the aftermath. Generating and executing separately
 * puts the plan on the map BEFORE it is spent — and turns a rejected order
 * from something you read about afterwards into something you can act on.
 *
 * ⚠ "EXECUTE" IS NOT FREE OF MODEL CALLS. The Counteraction Round is decided
 * after the first round has been fought — a reserve committed before seeing
 * what happened is not a reserve, it is a late start — so it cannot be
 * planned in advance and is asked for during execution. Two calls at
 * generate, two more at execute.
 *
 * WHY ORDERS CAN BE REJECTED, AND WHY THAT IS ON SCREEN
 *
 * Every option offered was generated by the rules. Anything a commander
 * returns that is not on that list is dropped — so a confused model produces
 * a unit that stood still, never an illegal move. The rejected orders panel
 * is the most important diagnostic here: it is the difference between "the
 * model played badly" and "the model asked for something impossible".
 *
 * The LLM commander calls the published `commanderTurn` query — see
 * data/commanderClient.ts. (This comment said it was not wired up for some
 * time after it was, which is its own small lesson about warnings.)
 */

