      // ground-scale transform and has `line-height:0` precisely so that its
      // box is the symbol's box; a bar in normal flow would grow it and every
      // counter would sit slightly above its grid square. Same reason the
      // badge strip is absolute.
      //
      // ⚠ NO BAR ON AN ENEMY, AND THAT IS NOT AN OVERSIGHT. Only own counters
      // and the umpire's "both" view carry a `strength` field at all: a
