/**
 * The board outline and the two halves, as GeoJSON.
 *
 * Extracted because THE BOARD CAN MOVE. Switching to the real raster recentres
 * it on the raster's coverage, and the sources are created once — so the same
 * geometry has to be available to the effect that updates them as to the one
 * that adds them, or the outline would stay drawn around a board that is no
 * longer there.
 */
function boardFeature(bounds: ReturnType<typeof boardBounds>): GeoJSON.Feature {
  return {
    type: "Feature",
    properties: {},
    geometry: { type: "Polygon", coordinates: [boardRing(bounds)] },
  };
}

function halvesFeature(bounds: ReturnType<typeof boardBounds>): GeoJSON.FeatureCollection {
  const mid = (bounds.north + bounds.south) / 2;
  return {
    type: "FeatureCollection",
    features: (
      [
        ["blue", bounds.south, mid],
        ["red", mid, bounds.north],
      ] as const
    ).map(([which, south, north]) => ({
      type: "Feature" as const,
      properties: { side: which },
      geometry: {
        type: "Polygon" as const,
        coordinates: [
          [
            [bounds.west, south],
            [bounds.east, south],
            [bounds.east, north],
            [bounds.west, north],
            [bounds.west, south],
          ],
        ],
      },
    })),
  };
}

/**
 * A short label for a plan line.
 *
 * The option's own `summary` is written to be read by a model inside a prompt
 * and is far too long for a map — it would cover the ground it describes. The
 * kind plus whichever modifiers are doing real work is what a reader needs at
 * a glance; the full summary stays in the orders panel, where there is room.
 */
function planLabel(line: PlanLine): string {
  const base =
    line.kind === "move"
      ? line.retreat
        ? "retreat"
        : "move"
      : line.kind === "assault"
        ? line.combined
          ? "assault \u00d7"
          : "assault"
        : line.smoke
          ? "smoke"
          : line.indirect
            ? "indirect"
            : line.combined
              ? "fire \u00d7"
              : "fire";

  // ⚠ NAME THE REFUSAL ON THE LINE ITSELF. "move" and "move that could not be
  // afforded" are the same word otherwise, and the second is the one the
  // player needs to act on — it is the cost of the command cap, which is the
  // only place that cap is visible.
  if (!line.refused) return base;
  return line.refusedReason === "beyond this turn's command capacity"
    ? `${base} — no command capacity`
    : `${base} — refused`;
}

/** Are two module sets the same? Used to show which preset is in force. */
function sameModules(a: ModuleFlags, b: ModuleFlags): boolean {
  return (Object.keys(b) as (keyof ModuleFlags)[]).every((key) => a[key] === b[key]);
}

/**
 * The command rating a hand-placed HQ gets.
 *
 * Every HQ in the scripted force lists is 3 — Squadron HQ, Company HQ and the
 * combined-arms one. Matching it means a hand-built battlegroup activates like
 * the list the rules were actually measured against, rather than on a figure
 * invented at the keyboard.
 */
/**
 * The map, if it is still alive.
 *
 * ⚠ A REMOVED MAP IS NOT A NULL MAP, AND `if (!map) return` DOES NOT CATCH
 * ONE. `remove()` tears the style out from under the instance; every accessor
 * afterwards throws "Cannot read properties of undefined (reading
 * 'getSource')" from inside MapLibre, which reads like a library bug and is
 * not one.
 *
 * Remounting the basemap to attach the elevation extension is what made that
 * window reachable. Toggling elevation destroys the old map and flips
 * `wantsDem` in the same commit, and the effect that repositions the board
 * depends on `wantsDem` — so it can fire holding a handle to a map that no
 * longer has a style, before the replacement has announced itself through
 * `onMapReady`.
 *
 * MapLibre publishes no "is this alive" predicate, so this asks the style
 * directly. One narrow cast in one place, rather than a try/catch wrapped
 * around every call in the file.
 */
function liveMap(map: maplibregl.Map | null): maplibregl.Map | null {
  if (!map) return null;
  return (map as unknown as { style?: unknown }).style ? map : null;
}

/**
 * Which DEM chunk a point needs, named the way the dataset names it.
 *
 * ⚠ PRINTED IN THE UI ON PURPOSE. "No elevation here" invites a shrug; "the
 * dataset has no c100_r015.tif" can be checked in ten seconds, and the answer
 * is either "add that cell" or "play somewhere it covers". The grid is
 * ELEVATION_STORE's — 2 degrees, from 180W/85N — and it is duplicated here
 * rather than imported because the package exports `cellFor` against its own
 * CellCoord type and this only needs the name.
 */
function demCellFor(point: LatLng): string {
  const col = Math.floor((point.lng + 180) / 2);
  const row = Math.floor((85 - point.lat) / 2);
  return `c${String(col).padStart(3, "0")}_r${String(row).padStart(3, "0")}`;
}

